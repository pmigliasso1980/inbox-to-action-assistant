"""Generate the production-readiness dashboard from committed evidence."""
from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def generate() -> str:
    audit = json.loads((ROOT / "runs/architecture-audit.json").read_text())
    cost = json.loads((ROOT / "reports/cost_model.json").read_text())
    graph = json.loads((ROOT / "runs/graph-orchestrator-summary.json").read_text())
    calls = [json.loads(x) for x in (ROOT / "runs/calls.jsonl").read_text().splitlines()]
    tokens = Counter()
    for row in calls:
        tokens[row["component"]] += row["input_tokens"] + row["output_tokens"] + row["cache_read_input_tokens"]
    tool_stats: dict[str, list[bool]] = {}
    for trace in (ROOT / "runs/tools").glob("item-*/trace.jsonl"):
        for event in map(json.loads, trace.read_text().splitlines()):
            if event.get("event") == "tool":
                tool_stats.setdefault(event["name"], []).append(bool(event.get("confirmed")))
    gate_rows = []
    for path in (ROOT / "runs/reflection").glob("item-*/iter-1.json"):
        gate_rows.append(not bool(json.loads(path.read_text()).get("gate")))
    token_total = sum(tokens.values())
    lines = ["# Production Readiness Dashboard", "", "> Generated by `reports/generate_dashboard.py`; do not edit manually.", "",
             f"Noise floor: **{audit['noise_floor']:.4f}**", "", "## Score progression", "",
             "| Stage | Score | Δ | Inside noise? |", "|---|---:|---:|---|"]
    for row in audit["rows"]:
        delta = row.get("delta_vs_previous")
        lines.append(f"| {row['stage']} | {row['mean_score']:.4f} | {'—' if delta is None else f'{delta:+.4f}'} | {'—' if delta is None else ('yes' if abs(delta) <= audit['noise_floor'] else 'no')} |")
    lines += ["", "## Cost and latency", "", "| Stage | Cost/item | p50 latency | p95 latency |", "|---|---:|---:|---:|"]
    for row in audit["rows"]:
        lines.append(f"| {row['stage']} | ${row['cost_per_item']:.5f} | {row['p50_latency_seconds'] if row['p50_latency_seconds'] is not None else 'not retained'} | {row['p95_latency_seconds'] if row['p95_latency_seconds'] is not None else 'not retained'} |")
    lines += ["", "## Cache effectiveness and token distribution", "", "| Component | Cache % | Token share |", "|---|---:|---:|"]
    for component, row in sorted(cost["by_component"].items()):
        lines.append(f"| {component} | {row['cache_effectiveness']:.1%} | {tokens[component] / max(1, token_total):.1%} |")
    lines += ["", "## Error rates", "", "| Tool or gate | Calls | Error/rejection rate |", "|---|---:|---:|"]
    for name, confirmations in sorted(tool_stats.items()):
        lines.append(f"| {name} | {len(confirmations)} | {(1 - sum(confirmations) / len(confirmations)):.1%} |")
    lines.append(f"| reflection deterministic gates | {len(gate_rows)} | {(1 - sum(gate_rows) / max(1, len(gate_rows))):.1%} |")
    lines += ["", "Injected fallback tests remain the authoritative proof that rejection paths execute.",
              "", "## Graph metrics (Rule 5)", "", "| Type | R/W | Readers | Cross-session | Verdict |", "|---|---:|---:|---:|---|"]
    for row in graph["rule5"]:
        lines.append(f"| {row['type']} | {row['read_write_ratio']:.2f} | {row['distinct_reader_roles']} | {row['cross_session_read_rate']:.0%} | {row['verdict']} |")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    (ROOT / "reports/dashboard.md").write_text(generate())
